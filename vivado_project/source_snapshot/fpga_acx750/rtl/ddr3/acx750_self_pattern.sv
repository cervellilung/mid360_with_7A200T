//============================================================================
// acx750_self_pattern -- DDR3 自检图案
//
// 关键约束：图案只能依赖 (x,y)，**不能依赖帧号**。
// 因为写侧和读侧各自按帧循环，绝对帧号不同；只有与帧号无关的图案
// 才能保证"读回的像素必然等于同一 (x,y) 的期望值"，比对才有意义。
//
// 图案分三段，便于人眼与自动比对同时判断：
//   x < 400   : 16 像素黑白棋盘（对 DDR3 数据线/地址线位错最敏感）
//   400..599  : 绿色行号斜坡（看行对齐）
//   >= 600    : 红=列斜率 / 蓝=行斜率（看列对齐）
//============================================================================
`timescale 1ns/1ps

module acx750_self_pattern (
  input  logic [11:0] x,
  input  logic [11:0] y,
  output logic [15:0] rgb
);

  // 注意：信号名不能用 checker —— 那是 SystemVerilog 保留字
  wire is_checker = x[4] ^ y[4];

  always_comb begin
    if (x < 12'd400)
      rgb = is_checker ? 16'hFFFF : 16'h0000;
    else if (x < 12'd600)
      rgb = {5'h00, y[5:0], 5'h00};
    else
      rgb = {x[4:0], 6'h00, y[4:0]};
  end

endmodule