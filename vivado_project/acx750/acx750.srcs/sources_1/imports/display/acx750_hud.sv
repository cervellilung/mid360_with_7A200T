//============================================================================
// acx750_hud -- HUD 叠加（像素时钟域）
//
// 与 disp_driver 的 DataReq 严格对齐：
//   en  : 本拍 DataReq（请求光栅顺序的下一个像素）
//   x,y : 本拍被请求像素的坐标
// 文本缓冲的读地址在本拍给出，读数据下一拍返回；同一拍 x,y 被打一拍得到
// dx,dy，正好与读回的字符合上。
//
// 叠加规则（不做任何"缩水"，字是 5x7 双倍放大）：
//   - 文本区内：底色压暗一半（base>>1），字符像素画白色
//   - 文本框四周画 1 像素青色边框
//   - 画面正中画十字线（青色），用于确认像素钟/同步正确
//============================================================================
`timescale 1ns/1ps

module acx750_hud (
  input  logic        pix_clk,
  input  logic        pix_rst_n,

  input  logic        en,           // == disp_driver.DataReq
  input  logic [11:0] x,            // 本拍请求像素的列
  input  logic [11:0] y,            // 本拍请求像素的行

  output logic [7:0]  txt_addr,     // 给 acx750_hud_ram 读口
  input  logic [7:0]  txt_data,     // 下一拍返回

  input  logic [15:0] base,         // 本拍底色像素
  output logic        hud_on,       // 1 = 用 hud_rgb 覆盖 base
  output logic [15:0] hud_rgb
);

  // 文本区几何：左上角 (8,8)，单元格 16x16，20 列 x 8 行
  localparam int TX0 = 8;
  localparam int TY0 = 8;
  localparam int CW  = 16;
  localparam int CH  = 16;
  localparam int NCOL = 20;
  localparam int NROW = 8;

  localparam int TX1 = TX0 + NCOL*CW;      // 328
  localparam int TY1 = TY0 + NROW*CH;      // 136

  //--------------------------------------------------------------------
  // 5x7 点阵字库（与 fpga_ac880 的 ar_video.sv 同一套字形，扩展到 A-Z）
  // 每字形 35bit，行 0 在最左（高位），列 0 在 bit4
  //--------------------------------------------------------------------
  function automatic [34:0] font(input logic [7:0] a);
    case (a)
      "0": font = 35'b01110_10001_10011_10101_11001_10001_01110;
      "1": font = 35'b00100_01100_00100_00100_00100_00100_01110;
      "2": font = 35'b01110_10001_00001_00010_00100_01000_11111;
      "3": font = 35'b11110_00001_00001_01110_00001_00001_11110;
      "4": font = 35'b00010_00110_01010_10010_11111_00010_00010;
      "5": font = 35'b11111_10000_10000_11110_00001_00001_11110;
      "6": font = 35'b01110_10000_10000_11110_10001_10001_01110;
      "7": font = 35'b11111_00001_00010_00100_01000_01000_01000;
      "8": font = 35'b01110_10001_10001_01110_10001_10001_01110;
      "9": font = 35'b01110_10001_10001_01111_00001_00001_01110;
      "A": font = 35'b01110_10001_10001_11111_10001_10001_10001;
      "B": font = 35'b11110_10001_10001_11110_10001_10001_11110;
      "C": font = 35'b01111_10000_10000_10000_10000_10000_01111;
      "D": font = 35'b11110_10001_10001_10001_10001_10001_11110;
      "E": font = 35'b11111_10000_10000_11110_10000_10000_11111;
      "F": font = 35'b11111_10000_10000_11110_10000_10000_10000;
      "G": font = 35'b01111_10000_10000_10111_10001_10001_01111;
      "H": font = 35'b10001_10001_10001_11111_10001_10001_10001;
      "I": font = 35'b01110_00100_00100_00100_00100_00100_01110;
      "J": font = 35'b00111_00010_00010_00010_00010_10010_01100;
      "K": font = 35'b10001_10010_10100_11000_10100_10010_10001;
      "L": font = 35'b10000_10000_10000_10000_10000_10000_11111;
      "M": font = 35'b10001_11011_10101_10101_10001_10001_10001;
      "N": font = 35'b10001_11001_10101_10011_10001_10001_10001;
      "O": font = 35'b01110_10001_10001_10001_10001_10001_01110;
      "P": font = 35'b11110_10001_10001_11110_10000_10000_10000;
      "Q": font = 35'b01110_10001_10001_10001_10101_10010_01101;
      "R": font = 35'b11110_10001_10001_11110_10100_10010_10001;
      "S": font = 35'b01111_10000_10000_01110_00001_00001_11110;
      "T": font = 35'b11111_00100_00100_00100_00100_00100_00100;
      "U": font = 35'b10001_10001_10001_10001_10001_10001_01110;
      "V": font = 35'b10001_10001_10001_10001_10001_01010_00100;
      "W": font = 35'b10001_10001_10001_10101_10101_11011_10001;
      "X": font = 35'b10001_10001_01010_00100_01010_10001_10001;
      "Y": font = 35'b10001_10001_01010_00100_00100_00100_00100;
      "Z": font = 35'b11111_00001_00010_00100_01000_10000_11111;
      "-": font = 35'b00000_00000_00000_11111_00000_00000_00000;
      ".": font = 35'b00000_00000_00000_00000_00000_00110_00110;
      ":": font = 35'b00000_00100_00100_00000_00100_00100_00000;
      "/": font = 35'b00001_00010_00010_00100_01000_01000_10000;
      "+": font = 35'b00000_00100_00100_11111_00100_00100_00000;
      default: font = 35'b0;
    endcase
  endfunction

  //--------------------------------------------------------------------
  // 本拍给出文本缓冲读地址
  //--------------------------------------------------------------------
  wire in_txt_now = (x >= TX0[11:0]) && (x < TX1[11:0]) &&
                    (y >= TY0[11:0]) && (y < TY1[11:0]);

  wire [11:0] rel_x = x - TX0[11:0];
  wire [11:0] rel_y = y - TY0[11:0];

  wire [4:0] col_now = rel_x[8:4];     // /16
  wire [2:0] row_now = rel_y[7:4];     // /16

  assign txt_addr = in_txt_now ? {row_now, col_now} : 8'h00;

  //--------------------------------------------------------------------
  // 打一拍坐标，与文本读数据对齐
  //--------------------------------------------------------------------
  logic [11:0] dx, dy;
  always_ff @(posedge pix_clk or negedge pix_rst_n) begin
    if (!pix_rst_n) begin
      dx <= '0;
      dy <= '0;
    end else begin
      dx <= x;
      dy <= y;
    end
  end

  wire in_txt = (dx >= TX0[11:0]) && (dx < TX1[11:0]) &&
                (dy >= TY0[11:0]) && (dy < TY1[11:0]);

  wire [11:0] srel_x = dx - TX0[11:0];
  wire [11:0] srel_y = dy - TY0[11:0];

  wire [2:0] fcol = srel_x[3:1];       // 0..7，用到 0..4
  wire [2:0] frow = srel_y[3:1];       // 0..7，用到 0..6

  logic [5:0] shift;
  always_comb begin
    if (frow < 3'd7 && fcol < 3'd5)
      shift = 6'd5*(6 - frow) + (4 - fcol);
    else
      shift = 6'd35;                    // 越界：35bit 右移 35 位得 0
  end

  wire [34:0] glyph = font(txt_data);
  wire        glyph_hit = in_txt && ((glyph >> shift) & 35'b1);

  // 文本框 1 像素青色边框
  wire border_h = in_txt && (srel_y <= 12'd1 || srel_y >= 12'd127);
  wire border_v = in_txt && (srel_x <= 12'd1 || srel_x >= 12'd319);
  wire border   = border_h || border_v;

  // 画面正中十字线（青色），用于确认同步与像素钟
  // 注意：信号名不能用 cross —— 那是 SystemVerilog 保留字
  wire cross_line = (dx == 12'd400) || (dy == 12'd240);

  assign hud_on  = in_txt || cross_line;
  assign hud_rgb = glyph_hit ? 16'hFFFF                                  // 字符：白
                 : border    ? 16'h07FF                                  // 边框：青
                 : cross_line? 16'h07FF                                  // 十字：青
                 :             {1'b0, base[15:1]};                       // 文本底：压暗一半

endmodule